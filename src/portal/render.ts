/**
 * 由注册表生成三类产物：
 *   1) 反向代理按 Host 分流的映射片段（兼容旧 nginx/网关）；
 *   2) 内网解析器覆盖片段（只覆盖 visibility=internal 的登记项）；
 *   3) Caddy 站点片段（internal 强制 bind + 来源白名单 + 404）。
 * 生成结果只依赖配置与注册表，随后按需 reload 服务。
 */
import {execFileSync} from 'node:child_process';
import {existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import type {Alias, PortalSettings} from '../config/index.js';
import {fqdnOf, readAliases} from './registry.js';
import {isInternal} from './providers.js';

export type RenderResult = {aliases: number; files: string[]; resolver: string; caddy: string[]};

const writeLines = (path: string, lines: string[]): void => {
  writeFileSync(path, lines.length ? `${lines.join('\n')}\n` : '');
};

const quote = (value: string): string => (/^[A-Za-z0-9_.:/\[\]-]+$/.test(value) ? value : JSON.stringify(value));

/** 生成单个 Caddy 站点；internal 站点必须使用默认私有 CA。 */
export function caddySite(settings: PortalSettings, item: Alias): string {
  const name = fqdnOf(settings, item);
  const target = `${item.scheme}://${item.host}:${item.port}`;
  const lines = [`# generated by aio-plugin-portal; alias=${item.alias} visibility=${item.visibility ?? 'internal'}`, `${name} {`, '\timport defaults'];
  if (isInternal(item)) {
    const bind = settings.caddy?.bind;
    if (bind) lines.push(`\tbind ${quote(bind)}`);
    const allow = settings.caddy?.allow?.length ? settings.caddy.allow : ['127.0.0.1/32'];
    lines.push(`\t@internal remote_ip ${allow.join(' ')}`);
    lines.push('\thandle @internal {', '\t\tencode gzip', `\t\treverse_proxy ${quote(target)}`, '\t}');
    lines.push('\thandle {', `\t\trespond ${settings.caddy?.denyStatus ?? 404}`, '\t}');
  } else {
    lines.push('\tencode gzip', `\treverse_proxy ${quote(target)}`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

/** 只清理带本工具标记的生成文件，人工维护的站点绝不删除。 */
function cleanGenerated(dir: string, prefix: string): string[] {
  if (!existsSync(dir)) return [];
  const removed: string[] = [];
  for (const name of readdirSync(dir)) {
    if (!name.startsWith(prefix) || !name.endsWith('.caddy')) continue;
    const path = join(dir, name);
    const text = readFileSync(path, 'utf8');
    if (text.startsWith('# generated by aio-plugin-portal')) {
      rmSync(path);
      removed.push(path);
    }
  }
  return removed;
}

export function renderCaddy(settings: PortalSettings): string[] {
  const caddy = settings.caddy;
  if (!caddy?.sitesDir) return [];
  const prefix = caddy.prefix ?? 'portal-';
  mkdirSync(caddy.sitesDir, {recursive: true});
  cleanGenerated(caddy.sitesDir, prefix);
  const files: string[] = [];
  for (const item of readAliases(settings).filter(entry => !entry.disabled)) {
    const path = join(caddy.sitesDir, `${prefix}${item.alias}.caddy`);
    // 同名文件若不是本工具生成的，说明有人在手工维护，拒绝覆盖而不是悄悄顶掉。
    if (existsSync(path) && !readFileSync(path, 'utf8').startsWith('# generated by aio-plugin-portal')) {
      throw new Error(`站点文件 ${path} 不是本工具生成的，拒绝覆盖；请改名或手工迁移该站点`);
    }
    writeFileSync(path, caddySite(settings, item));
    files.push(path);
  }
  return files;
}

export function render(settings: PortalSettings): RenderResult {
  const s = settings;
  const aliases = readAliases(s).filter(entry => !entry.disabled);
  const dir = s.portal.aliasesDir!;
  mkdirSync(dir, {recursive: true});

  const map: string[] = [];
  const scheme: string[] = [];
  const host: string[] = [];
  for (const item of aliases) {
    const name = fqdnOf(s, item);
    const target = `${item.host}:${item.port}`;
    map.push(`    ${name}  ${target};`);
    scheme.push(`    ${name}  ${item.scheme};`);
    host.push(`    ${name}  ${target};`);
  }
  const files = [
    join(dir, `${s.portal.mapPrefix}.map`),
    join(dir, `${s.portal.mapPrefix}.scheme`),
    join(dir, `${s.portal.mapPrefix}.host`),
  ];
  writeLines(files[0], map);
  writeLines(files[1], scheme);
  writeLines(files[2], host);

  const resolver = s.resolver.configFile!;
  mkdirSync(join(resolver, '..'), {recursive: true});
  const overrides =
    s.mode === 'none' || !s.lanIp
      ? []
      : aliases.filter(item => isInternal(item)).map(item => `address=/${fqdnOf(s, item)}/${s.lanIp}`);
  const header = '# 由 aio-portal 生成，请勿手改；改注册表后执行 sync';
  const lines = s.resolver.fragment
    ? [header, ...overrides]
    : [
        header,
        `port=${s.resolver.port}`,
        `listen-address=${s.lanIp || '127.0.0.1'}`,
        'bind-interfaces',
        'no-resolv',
        'no-hosts',
        'cache-size=1000',
        ...s.resolver.upstreams.map(up => `server=${up}`),
        ...overrides,
      ];
  writeFileSync(resolver, `${lines.join('\n')}\n`);
  return {aliases: aliases.length, files, resolver, caddy: renderCaddy(s)};
}

const run = (program: string, args: string[]): {code: number; out: string} => {
  try {
    const out = execFileSync(program, args, {encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe']});
    return {code: 0, out: out.trim()};
  } catch (error) {
    const err = error as {status?: number; stdout?: string; stderr?: string; message?: string};
    return {code: err.status ?? 1, out: `${err.stdout ?? ''}${err.stderr ?? ''}`.trim() || (err.message ?? '')};
  }
};

export function validateCaddy(settings: PortalSettings): string {
  const s = settings;
  if (!s.caddy?.binary) return '已跳过 caddy validate（未配置 caddy.binary）';
  const config = s.caddy.sitesDir ? join(s.caddy.sitesDir, '..', 'Caddyfile') : '';
  if (!existsSync(config)) return `Caddy 配置校验失败：找不到 ${config}`;
  const args = ['validate', '--config', config];
  const test = run(s.caddy.binary, args);
  return test.code === 0 ? 'Caddy 配置校验通过' : `Caddy 配置校验失败：${test.out}`;
}

export function reloadCaddy(settings: PortalSettings): string {
  const command = settings.caddy?.reload;
  if (!command) return '已跳过 Caddy 热加载（未配置 caddy.reload）';
  const [program, ...args] = command.trim().split(/\s+/);
  const result = run(program, args);
  return result.code === 0 ? 'Caddy 已热加载' : `Caddy 热加载失败：${result.out}`;
}

/** 校验并热加载内网解析器；未安装 dnsmasq 或服务不存在时给出可读提示。 */
export function reloadResolver(settings: PortalSettings): string {
  if (settings.resolver.provider === 'none') return '已跳过内网解析刷新（resolver.provider=none）';
  // systemd 服务进程的 PATH 常不含 /usr/sbin；二进制按 配置 > PATH > 常见路径 解析。
  const binary = settings.resolver.dnsmasqBinary ?? (existsSync('/usr/sbin/dnsmasq') ? '/usr/sbin/dnsmasq' : 'dnsmasq');
  const test = run(binary, ['--test', `--conf-file=${settings.resolver.configFile}`]);
  if (test.code !== 0) return `解析配置校验失败：${test.out}`;
  if (settings.resolver.service) {
    const reload = run('systemctl', ['reload-or-restart', settings.resolver.service]);
    return reload.code === 0 ? '内网解析已刷新' : `内网解析刷新失败：${reload.out}`;
  }
  return '解析配置已生成（未配置 resolver.service，未触碰宿主服务）';
}
