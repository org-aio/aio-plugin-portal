/**
 * 登记的「删干净」：一条别名在三处留下痕迹——
 *   1) Caddy 站点片段（`<prefix><alias>.caddy`）
 *   2) 内网解析覆盖（dnsmasq 片段里的 `address=/<fqdn>/<ip>`）
 *   3) 分流映射产物（`.map` / `.scheme` / `.host`）
 * 注册表 filter 掉一条记录只是第 0 步。这里负责跟踪并**反向校验**：
 * 重写产物后再读回，确认没有任何一行仍引用该 fqdn；不干净就整体回滚并抛错。
 * 只清理带本工具标记的生成文件，人工维护的站点文件绝不删除。
 */
import {existsSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import type {PortalSettings} from '../config/index.js';
import {fqdnOf} from './registry.js';

const MARK = '# generated by aio-plugin-portal';
const OTHER_MARK = '# 由 aio-portal 生成';

export type ArtifactState = {
  caddySite?: {path: string; text: string};
  resolver?: {path: string; text: string};
  maps: {path: string; text: string}[];
};

export type TeardownEvidence = {
  fqdn: string;
  removed: string[];
  verified: {artifact: string; ok: boolean; detail: string}[];
};

/** 收集与某条别名相关的全部产物原文，作为回滚快照。 */
export function captureArtifacts(settings: PortalSettings, alias: string): ArtifactState {
  const state: ArtifactState = {maps: []};
  const sitesDir = settings.caddy?.sitesDir;
  if (sitesDir) {
    const path = join(sitesDir, `${settings.caddy?.prefix ?? 'portal-'}${alias}.caddy`);
    if (existsSync(path)) state.caddySite = {path, text: readFileSync(path, 'utf8')};
  }
  const resolver = settings.resolver.configFile;
  if (resolver && existsSync(resolver)) state.resolver = {path: resolver, text: readFileSync(resolver, 'utf8')};
  const dir = settings.portal.aliasesDir;
  if (dir) {
    for (const name of [`${settings.portal.mapPrefix}.map`, `${settings.portal.mapPrefix}.scheme`, `${settings.portal.mapPrefix}.host`]) {
      const path = join(dir, name);
      if (existsSync(path)) state.maps.push({path, text: readFileSync(path, 'utf8')});
    }
  }
  return state;
}

/** 回滚：把快照原样写回，并还原被删除的站点文件。 */
export function restoreArtifacts(state: ArtifactState): void {
  if (state.caddySite) writeFileSync(state.caddySite.path, state.caddySite.text);
  if (state.resolver) writeFileSync(state.resolver.path, state.resolver.text);
  for (const map of state.maps) writeFileSync(map.path, map.text);
}

/**
 * 删除带本工具标记的站点文件。返回被删除的路径。
 * 标记不符时拒绝删除，避免误删人工维护的站点。
 */
export function removeCaddySite(settings: PortalSettings, alias: string): string[] {
  const sitesDir = settings.caddy?.sitesDir;
  if (!sitesDir) return [];
  const path = join(sitesDir, `${settings.caddy?.prefix ?? 'portal-'}${alias}.caddy`);
  if (!existsSync(path)) return [];
  const text = readFileSync(path, 'utf8');
  if (!text.startsWith(MARK)) return [];
  rmSync(path);
  return [path];
}

const escapeRe = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * 反向校验：删除后重新读文件，确认没有残留引用。
 * 这里是「删干净」的判据——不看返回值，只看磁盘现状。
 */
export function verifyGone(settings: PortalSettings, alias: string, suffix?: string): TeardownEvidence['verified'] {
  // 必须带上记录自身的后缀覆盖，否则校验的是另一条 fqdn，残留会被误判为「已删干净」。
  const fqdn = fqdnOf(settings, {alias, suffix});
  const pattern = new RegExp(`(^|[^A-Za-z0-9.-])${escapeRe(fqdn)}([^A-Za-z0-9-]|$)`, 'm');
  const results: TeardownEvidence['verified'] = [];
  const sitesDir = settings.caddy?.sitesDir;
  if (sitesDir) {
    const path = join(sitesDir, `${settings.caddy?.prefix ?? 'portal-'}${alias}.caddy`);
    // 判据只针对本工具生成的产物：别人手工维护的同名文件既不该被删除，也不该算作残留。
    const owned = existsSync(path) && readFileSync(path, 'utf8').startsWith(MARK);
    results.push({
      artifact: 'caddy-site',
      ok: !owned,
      detail: !owned ? (existsSync(path) ? '同名文件非本工具生成，已保留' : '站点文件已移除') : `仍存在本工具产物 ${path}`,
    });
    // 扫描范围：本工具命名的 portal-* 文件，或带本工具标记的文件。
    // 与别名同名的人工站点（非 portal- 前缀、无标记）属于别人的资产，不计入残留。
    const others = existsSync(sitesDir) ? readResidual(sitesDir, fqdn, settings.caddy?.prefix ?? 'portal-', alias) : [];
    results.push({
      artifact: 'caddy-scan',
      ok: others.length === 0,
      detail: others.length ? `其他站点仍引用 ${fqdn}: ${others.join(', ')}` : '站点目录无残留引用',
    });
  }
  const resolver = settings.resolver.configFile;
  if (resolver) {
    const text = existsSync(resolver) ? readFileSync(resolver, 'utf8') : '';
    // 传进来的 configFile 可能指向一个未被使用的片段；同一目录里的其它解析片段也算范围，
    // 否则「产物写在别处」的残留会直接漏过校验。
    const extra = existsSync(dirname(resolver))
      ? readdirSync(dirname(resolver)).filter(name => name.endsWith('.conf') && join(dirname(resolver), name) !== resolver).map(name => join(dirname(resolver), name))
      : [];
    const dirty = [resolver, ...extra].filter(path => existsSync(path) && pattern.test(readFileSync(path, 'utf8')));
    results.push({artifact: 'resolver', ok: dirty.length === 0, detail: dirty.length ? `解析片段仍含 ${fqdn}: ${dirty.join(', ')}` : '解析片段已清除'});
  }
  const dir = settings.portal.aliasesDir;
  if (dir) {
    for (const name of [`${settings.portal.mapPrefix}.map`, `${settings.portal.mapPrefix}.scheme`, `${settings.portal.mapPrefix}.host`]) {
      const path = join(dir, name);
      const text = existsSync(path) ? readFileSync(path, 'utf8') : '';
      results.push({artifact: `map:${name}`, ok: !pattern.test(text), detail: pattern.test(text) ? `${name} 仍含 ${fqdn}` : `${name} 已清除`});
    }
  }
  return results;
}

function readResidual(dir: string, fqdn: string, prefix: string, alias: string): string[] {
  const hits: string[] = [];
  const host = new RegExp(`(^|[^A-Za-z0-9.-])${escapeRe(fqdn)}([^A-Za-z0-9-]|$)`, 'm');
  for (const name of readdirSync(dir)) {
    if (!name.endsWith('.caddy')) continue;
    const path = join(dir, name);
    if (!statSync(path).isFile()) continue;
    const text = readFileSync(path, 'utf8');
    // 扫描范围：带本工具标记的文件，外加本工具为「别的记录」命名的 prefix* 文件。
    // 别人在同目录下手工维护的站点（没有标记、也不是本工具命名）属于他们的资产，不计入残留。
    // 带标记的文件即使后来被人工改过仍算残留：正文里还挂着这个域名就不算删干净。
    if (!text.startsWith(MARK) && !name.startsWith(prefix)) continue;
    if (!text.startsWith(MARK) && name === `${prefix}${alias}.caddy`) continue; // 本记录的同一个文件，上面已校验
    if (host.test(text)) hits.push(name);
  }
  return hits;
}

export {MARK, OTHER_MARK};
